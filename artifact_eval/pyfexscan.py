def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="pyfexscan",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    src = parser.add_mutually_exclusive_group(required=True)
    src.add_argument("--sample", metavar="RANK|ID",
                     help="Run a prepared calibrated sample (by rank or sample_id) end to end.")
    src.add_argument("--program", metavar="PATH",
                     help="Run an arbitrary Python target (file, or module name with --module).")
    src.add_argument("--trace", nargs="+", metavar="PATH", default=None,
                     help="Classify existing behavior_trace.jsonl / .simple.log file(s); no execution.")

    run = parser.add_argument_group("PyFEX run options (for --sample / --program)")
    run.add_argument("--pyfex", default=str(DEFAULT_INTERPRETER),
                     help=f"PyFEX interpreter path. Default: {DEFAULT_INTERPRETER}.")
    run.add_argument("--module", action="store_true", help="Treat --program as a module name (-m).")
    run.add_argument("--cwd", default=None, help="Working directory for the target.")
    run.add_argument("--scope-dir", default=None,
                     help="In-scope directory for tracing. Default: the target's directory.")
    run.add_argument("--network", choices=("blocked", "host"), default="blocked",
                     help="Network policy for the target. Default: blocked.")
    run.add_argument("--timeout", type=float, default=30.0, help="Per-run timeout (s). Default: 30.")
    run.add_argument("--force-exec-limit", type=int, default=20, help="Total forced-execution forks.")
    run.add_argument("--force-exec-location-limit", type=int, default=2, help="Forks per bytecode location.")
    run.add_argument("--loop-limit", type=int, default=50, help="Per-loop iteration cap.")
    run.add_argument("--provenance-mode", choices=("default", "flat", "recursive"), default="recursive",
                     help="PYFEX_PROVENANCE_MODE for synthetic objects. Default: recursive.")
    run.add_argument("program_args", nargs=argparse.REMAINDER,
                     help="Args passed to the target (prefix with -- ).")

    llm = parser.add_argument_group("LLM classifier")
    llm.add_argument("--llm", choices=("openai", "anthropic"), default="openai",
                     help="LLM backend. Default: openai (the paper uses gpt-4.1-mini).")
    llm.add_argument("--model", default=None,
                     help="Model id. Default: gpt-4.1-mini (openai) / claude-sonnet-5 (anthropic).")
    llm.add_argument("--temperature", type=float, default=0.0, help="Sampling temperature. Default: 0.")
    llm.add_argument("--no-llm", action="store_true",
                     help="Do not call any LLM; just build the prompt/trace (offline dry run).")

    fmt = parser.add_argument_group("trace formatting")
    fmt.add_argument("--max-arg-repr", type=int, default=200, help="Max chars per argument repr.")
    fmt.add_argument("--max-lines", type=int, default=8000, help="Max call lines included.")
    fmt.add_argument("--max-provenance", type=int, default=300, help="Max synthetic-object lineages.")
    fmt.add_argument("--max-chars", type=int, default=200_000, help="Hard cap on prompt trace size.")
    fmt.add_argument("--full-path", action="store_true", help="Keep absolute caller paths.")

    out = parser.add_argument_group("output")
    out.add_argument("-o", "--output", default=None, help="Write the JSON report to this path.")
    out.add_argument("--save-prompt", default=None, help="Also write the full LLM prompt to this path.")
    out.add_argument("--print-prompt", action="store_true", help="Print the full prompt to stdout.")

    args = parser.parse_args(argv)
    # `program_args` collects trailing REMAINDER; strip a leading `--`.
    if args.program_args and args.program_args[0] == "--":
        args.program_args = args.program_args[1:]
    return args


def default_model(backend: str) -> str:
    return "gpt-4.1-mini" if backend == "openai" else "claude-sonnet-5"


# Friendly shorthands -> canonical model ids. Any string not listed here is
# passed to the backend unchanged, so exact ids always work too.
MODEL_ALIASES = {
    "gpt4.1mini": "gpt-4.1-mini",
    "gpt5.4mini": "gpt-5.4-mini",
    "gpt-5.4mini": "gpt-5.4-mini",
}


def resolve_model(name: str) -> str:
    key = name.strip().lower()
    if key in MODEL_ALIASES:
        return MODEL_ALIASES[key]
    return MODEL_ALIASES.get(key.replace("_", "-"), name.strip())


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    scratch = Path(os.environ.get("PYFEXSCAN_OUT", REPO_ROOT / "artifact_eval" / "pyfexscan_out"))

    if args.trace is not None:
        target_label = ", ".join(args.trace)
        trace_paths = [Path(p) for p in args.trace]
    elif args.sample is not None:
        target_label = f"sample:{args.sample}"
        trace_paths = acquire_from_sample(args)
    else:
        target_label = args.program
        out_dir = scratch / re.sub(r"\W+", "_", Path(args.program).stem)[:60]
        out_dir.mkdir(parents=True, exist_ok=True)
        trace_paths = acquire_from_program(args, out_dir)

    base_dir = None if args.full_path else REPO_ROOT
    formatted = format_traces(
        trace_paths,
        base_dir=base_dir,
        max_arg_repr=args.max_arg_repr,
        max_lines=args.max_lines,
        max_provenance=args.max_provenance,
        max_chars=args.max_chars,
    )
    prompt = LLM_PROMPT_TEMPLATE.format(trace=formatted.text)

    if args.save_prompt:
        Path(args.save_prompt).write_text(prompt, encoding="utf-8")
    if args.print_prompt:
        print(prompt)

    print(
        f"[pyfexscan] target={target_label} traces={len(formatted.sources)} "
        f"calls={formatted.call_events} synthetic_objects={formatted.provenance_count} "
        f"files={len(formatted.files)} truncated={formatted.truncated}",
        file=sys.stderr,
    )

    report: dict[str, Any] = {
        "target": target_label,
        "trace_sources": formatted.sources,
        "call_events": formatted.call_events,
        "synthetic_object_provenance": formatted.provenance_count,
        "distinct_files": len(formatted.files),
        "trace_truncated": formatted.truncated,
    }

    if args.no_llm:
        report["verdict"] = None
        report["note"] = "LLM classification skipped (--no-llm); prompt was built only."
        print("[pyfexscan] --no-llm: prompt built, classification skipped.", file=sys.stderr)
    else:
        model = resolve_model(args.model) if args.model else default_model(args.llm)
        verdict = classify(prompt, args.llm, model, args.temperature)
        report["verdict"] = {
            "result": verdict.result,
            "confidence": verdict.confidence,
            "reason": verdict.reason,
        }
        report["llm"] = {"backend": verdict.backend, "model": verdict.model}
        report["llm_raw_response"] = verdict.raw
        print()
        print(f"  Result:     {verdict.result}")
        print(f"  Confidence: {verdict.confidence}")
        print(f"  Model:      {verdict.backend}:{verdict.model}")
        print(f"  Reason:     {verdict.reason}")
        print()

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
        print(f"[pyfexscan] report written to {out_path}", file=sys.stderr)

    verdict_obj = report.get("verdict")
    if isinstance(verdict_obj, dict) and verdict_obj.get("result", "").lower() == "malicious":
        return 1
    return 0


