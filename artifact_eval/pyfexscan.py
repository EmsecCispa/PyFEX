#!/usr/bin/env python3
"""PyFEXScan -- the LLM-backed malware detector built on top of PyFEX (paper Section 5).

PyFEXScan pairs two cooperating roles, exactly as described in the paper:

  1. PyFEX -- the *analysis engine*. It runs the target package under the
     instrumented CPython interpreter with resilient crash recovery, forced
     execution, and branch merging enabled, producing a structured,
     strace-style behavior trace of function calls, methods, and arguments.
     Synthetic ("Dummy") objects synthesized during crash recovery do not
     hold a concrete value; they carry a *symbolic provenance lineage* that
     records where they came from and how they were used.

  2. The LLM component -- reads *only* the trace that PyFEX produced and
     decides whether the package is malicious. It does not execute code,
     recover paths, or synthesize state (that is PyFEX's job); it interprets
     the behavior and the synthetic-object provenance to reconstruct data
     flow and render a verdict. The paper uses GPT-4.1-mini here.

This script wires the two together end to end:

    target  ->  PyFEX run (trace)  ->  format trace  ->  LLM  ->  {result, confidence, reason}

Trace acquisition supports three modes:

  --sample RANK|ID   run a prepared calibrated sample end-to-end (reuses
                     run_one_calibrated_sample.py) and gather its traces
  --program PATH     run an arbitrary target under PyFEX (reuses
                     run_pyfex_program.py) and use the resulting trace
  --trace PATH ...   classify one or more existing behavior_trace.jsonl (or
                     .simple.log) files without executing anything -- works
                     with no interpreter build and no network

The LLM prompt is Listing 8 from the paper's appendix, reproduced verbatim.
The default backend is OpenAI gpt-4.1-mini (the paper's choice); an Anthropic
backend and an offline --no-llm mode (emit the prompt only) are also provided.

    SAFETY: --sample and --program EXECUTE code that may be real malware.
    Only run them inside a disposable, network-isolated VM or container.
    Both keep the network blocked by default (see the repo README).
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import re
import subprocess
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Iterator


REPO_ROOT = Path(__file__).resolve().parents[1]
ARTIFACT_DIR = REPO_ROOT / "artifact_eval"
SAMPLES_DIR = ARTIFACT_DIR / "samples"
RUN_PYFEX = ARTIFACT_DIR / "run_pyfex_program.py"
RUN_ONE_SAMPLE = ARTIFACT_DIR / "run_one_calibrated_sample.py"
DEFAULT_INTERPRETER = REPO_ROOT / "PyFEX-core" / "python"


# ---------------------------------------------------------------------------
# The LLM prompt: Listing 8 from the paper (Appendix A.4), reproduced verbatim.
# `{trace}` replaces the paper's "[INSERT EXECUTION TRACE HERE]" placeholder.
# ---------------------------------------------------------------------------
LLM_PROMPT_TEMPLATE = """\
You are an expert malware analyst specializing in Python software supply chain security.
Your task is to analyze the provided execution trace of a Python package to determine
if it exhibits malicious behavior.
# Input Description
The input is a structured log of function calls, methods, and arguments captured
during the dynamic execution of the package.
# Critical Instruction on Synthetic Objects
The trace may contain Synthetic Objects generated by the analysis engine to recover \
from runtime crashes (e.g., offline servers, missing dependencies). You must treat \
the string representation of these objects not as literal strings, but as symbolic \
provenance properties.
Format: These properties describe the object creation and consumption history (e.g., \
'ADD(Dummy_A, 1)').
Task: You must trace the lineage of these objects to understand the semantic context \
of the data flow.
# Output Format
Provide your analysis in the following JSON format:
{{
  "result": "Malicious" | "Benign",
  "confidence": "High" | "Medium" | "Low",
  "reason": "A concise explanation citing specific behaviors and data flows from the \
trace that justifies the verdict."
}}
# Execution Trace
{trace}
"""


# ---------------------------------------------------------------------------
# Trace formatting
#
# The LLM only ever sees this text, so it must (a) read like an strace-style
# call log and (b) preserve the symbolic provenance of Synthetic Objects, which
# the prompt explicitly asks the model to reason about. We therefore render each
# function_call as `[file:line] func(args)` and collect every unique
# synthetic-object lineage into a provenance appendix keyed SO#1, SO#2, ...
# ---------------------------------------------------------------------------

# Keys under which a value dict may carry a synthetic-object provenance lineage.
# `dummy_trace` is emitted in the default (flat) provenance mode; `provenance`
# and `trace` are emitted by PYFEX_PROVENANCE_MODE=recursive.
_PROVENANCE_KEYS = ("dummy_trace", "provenance", "trace")


@dataclass
class TraceFormat:
    text: str
    call_events: int = 0
    total_rows: int = 0
    provenance_count: int = 0
    files: set[str] = field(default_factory=set)
    truncated: bool = False
    sources: list[str] = field(default_factory=list)


def _truncate(text: str, limit: int) -> str:
    if limit <= 0 or len(text) <= limit:
        return text
    if limit <= 3:
        return text[:limit]
    return text[: limit - 3] + "..."


def _short_path(path: str, base_dir: Path | None) -> str:
    if not path:
        return "<unknown>"
    if path.startswith("<") and path.endswith(">"):
        return path
    if base_dir is not None:
        try:
            return str(Path(path).resolve().relative_to(base_dir))
        except (OSError, ValueError):
            pass
    return path


def _render_value(value: Any, limit: int, prov_sink: list[str]) -> str:
    """Render one argument/kwarg value to a compact string, siphoning any
    synthetic-object provenance lineage into `prov_sink` as a side effect."""
    if isinstance(value, dict):
        for key in _PROVENANCE_KEYS:
            lineage = value.get(key)
            if isinstance(lineage, str) and lineage.strip():
                prov_sink.append(lineage.strip())
        rendered = value.get("repr")
        if rendered is not None:
            return _truncate(str(rendered), limit)
        rendered_type = value.get("type")
        if rendered_type:
            return f"<{rendered_type}>"
    return _truncate(repr(value), limit)


def _format_call_row(row: dict[str, Any], base_dir: Path | None, limit: int,
                     prov_sink: list[str]) -> str | None:
    if row.get("event") != "function_call":
        return None
    caller = row.get("caller") if isinstance(row.get("caller"), dict) else {}
    file_name = _short_path(str(caller.get("file") or ""), base_dir)
    line = caller.get("line") or "?"
    function = row.get("function") or "<unknown>"

    parts = [_render_value(arg, limit, prov_sink) for arg in row.get("args", [])]
    kwargs = row.get("kwargs", {})
    if isinstance(kwargs, dict):
        for key in kwargs:
            parts.append(f"{key}={_render_value(kwargs[key], limit, prov_sink)}")
    return f"[{file_name}:{line}] {function}({', '.join(parts)})"


def _iter_rows(path: Path) -> Iterator[dict[str, Any] | str]:
    """Yield dict rows from a .jsonl trace, or raw strings from an already
    simplified .simple.log (which we pass through untouched)."""
    is_jsonl = path.suffix == ".jsonl"
    with path.open("r", encoding="utf-8", errors="replace") as fp:
        for raw in fp:
            line = raw.strip()
            if not line:
                continue
            if not is_jsonl:
                yield line
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(obj, dict):
                yield obj


def format_traces(paths: Iterable[Path], *, base_dir: Path | None, max_arg_repr: int,
                  max_lines: int, max_provenance: int, max_chars: int) -> TraceFormat:
    """Turn one or more PyFEX behavior traces into the single strace-style block
    the LLM classifies. Multiple traces (e.g. one per package entry point) are
    concatenated into one package-level view, mirroring PyFEXScan's granularity
    of a verdict per package."""
    result = TraceFormat(text="")
    lines: list[str] = []
    provenance: list[str] = []
    seen_provenance: set[str] = set()

    for path in paths:
        if not path.is_file():
            continue
        result.sources.append(str(path))
        header = f"# ---- trace: {_short_path(str(path), REPO_ROOT)} ----"
        section_added = False
        for row in _iter_rows(path):
            result.total_rows += 1
            if isinstance(row, str):
                rendered = row  # already-simplified .simple.log line
            else:
                rendered = _format_call_row(row, base_dir, max_arg_repr, provenance)
                if rendered is None:
                    continue
                result.call_events += 1
                caller = row.get("caller") if isinstance(row.get("caller"), dict) else {}
                if caller.get("file"):
                    result.files.add(str(caller["file"]))
            if not section_added:
                lines.append(header)
                section_added = True
            if len(lines) < max_lines:
                lines.append(rendered)
            else:
                result.truncated = True

        # Dedupe provenance lineages as they accumulate, preserving first-seen order.
        for lineage in provenance:
            if lineage not in seen_provenance:
                seen_provenance.add(lineage)
        provenance = []

    call_block = "\n".join(lines) if lines else "(no in-scope function calls were recorded)"

    ordered_provenance = list(seen_provenance)
    result.provenance_count = len(ordered_provenance)
    prov_block = ""
    if ordered_provenance:
        chunks = ["", "# ---- Synthetic Object provenance (symbolic lineage; NOT literal strings) ----"]
        for idx, lineage in enumerate(ordered_provenance[:max_provenance], 1):
            chunks.append(f"[SO#{idx}]")
            chunks.append(textwrap.indent(lineage, "    "))
        if len(ordered_provenance) > max_provenance:
            chunks.append(f"... {len(ordered_provenance) - max_provenance} more synthetic-object lineages omitted ...")
        prov_block = "\n".join(chunks)

    text = call_block + ("\n" + prov_block if prov_block else "")
    if max_chars > 0 and len(text) > max_chars:
        text = text[:max_chars] + "\n... [trace truncated to fit the model context] ..."
        result.truncated = True
    result.text = text
    return result


