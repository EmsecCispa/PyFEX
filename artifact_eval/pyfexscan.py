@dataclass
class Verdict:
    result: str
    confidence: str
    reason: str
    raw: str
    model: str
    backend: str


def _parse_verdict_json(raw: str) -> dict[str, str]:
    """Extract the {result, confidence, reason} object from the model reply,
    tolerating markdown fences or surrounding prose."""
    text = raw.strip()
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\n?", "", text)
        text = re.sub(r"\n?```$", "", text).strip()
    try:
        obj = json.loads(text)
    except json.JSONDecodeError:
        start, end = text.find("{"), text.rfind("}")
        if start == -1 or end <= start:
            raise ValueError("model reply did not contain a JSON object")
        obj = json.loads(text[start : end + 1])
    if not isinstance(obj, dict):
        raise ValueError("model reply JSON was not an object")
    return {
        "result": str(obj.get("result", "Unknown")),
        "confidence": str(obj.get("confidence", "Unknown")),
        "reason": str(obj.get("reason", "")),
    }


def classify_openai(prompt: str, model: str, temperature: float) -> tuple[str, str]:
    try:
        from openai import OpenAI
    except ImportError as exc:  # pragma: no cover - depends on environment
        raise SystemExit(
            "The 'openai' package is required for --llm openai. Install it with "
            "`pip install openai` and set OPENAI_API_KEY, or use --no-llm to emit "
            "the prompt only."
        ) from exc
    client = OpenAI()
    messages = [{"role": "user", "content": prompt}]
    # Start with the params GPT-4.1 accepts, then progressively drop the ones a
    # newer model rejects (the GPT-5 reasoning family only allows the default
    # temperature and may not accept response_format), retrying each time.
    kwargs: dict[str, Any] = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "response_format": {"type": "json_object"},
    }
    last_exc: Exception | None = None
    for _ in range(4):
        try:
            resp = client.chat.completions.create(**kwargs)
            return resp.choices[0].message.content or "", model
        except Exception as exc:  # noqa: BLE001 - surface a clean, actionable error
            last_exc = exc
            name = type(exc).__name__
            msg = str(exc).lower()
            if name == "NotFoundError" or "does not exist" in msg or "model_not_found" in msg:
                raise SystemExit(
                    f"OpenAI rejected model {model!r}: {exc}\n"
                    "Pass a valid --model (e.g. gpt-4.1-mini, gpt-5-mini, gpt-5.4-mini)."
                ) from exc
            if "response_format" in kwargs and "response_format" in msg:
                kwargs.pop("response_format")
                continue
            if "temperature" in kwargs and "temperature" in msg:
                kwargs.pop("temperature")  # fall back to the model's default
                continue
            raise
    raise SystemExit(f"OpenAI request failed for model {model!r}: {last_exc}")


def classify_anthropic(prompt: str, model: str, temperature: float) -> tuple[str, str]:
    try:
        from anthropic import Anthropic
    except ImportError as exc:  # pragma: no cover - depends on environment
        raise SystemExit(
            "The 'anthropic' package is required for --llm anthropic. Install it "
            "with `pip install anthropic` and set ANTHROPIC_API_KEY, or use "
            "--no-llm to emit the prompt only."
        ) from exc
    client = Anthropic()
    resp = client.messages.create(
        model=model,
        max_tokens=1024,
        temperature=temperature,
        messages=[{"role": "user", "content": prompt}],
    )
    text = "".join(block.text for block in resp.content if getattr(block, "type", None) == "text")
    return text, model


def classify(prompt: str, backend: str, model: str, temperature: float) -> Verdict:
    if backend == "openai":
        raw, used = classify_openai(prompt, model, temperature)
    elif backend == "anthropic":
        raw, used = classify_anthropic(prompt, model, temperature)
    else:  # pragma: no cover - guarded by argparse choices
        raise SystemExit(f"unknown LLM backend: {backend}")
    parsed = _parse_verdict_json(raw)
    return Verdict(
        result=parsed["result"],
        confidence=parsed["confidence"],
        reason=parsed["reason"],
        raw=raw,
        model=used,
        backend=backend,
    )


# ---------------------------------------------------------------------------
# Trace acquisition -- run PyFEX (or reuse an existing trace)
# ---------------------------------------------------------------------------

def _require_interpreter(interp: Path) -> None:
    if not interp.exists():
        raise SystemExit(
            f"PyFEX interpreter not found: {interp}\n"
            "Build it first:  ( cd PyFEX-core && ./configure && make -j\"$(nproc)\" )\n"
            "Or classify an already-generated trace with --trace <path>."
        )


def _pyfex_env(provenance_mode: str) -> dict[str, str]:
    env = os.environ.copy()
    # PYFEX_PROVENANCE_MODE is not cleared by the wrappers, so it flows through
    # to the interpreter. 'recursive' records nested symbolic provenance (the
    # ADD(Dummy_A, 1)-style expressions the LLM prompt references).
    if provenance_mode != "default":
        env["PYFEX_PROVENANCE_MODE"] = provenance_mode
    return env


def acquire_from_program(args: argparse.Namespace, out_dir: Path) -> list[Path]:
    interp = Path(args.pyfex).resolve()
    _require_interpreter(interp)
    program = Path(args.program)
    scope_dir = Path(args.scope_dir).resolve() if args.scope_dir else (
        program.resolve().parent if not args.module else Path.cwd()
    )
    trace_log = out_dir / "behavior_trace.jsonl"
    runtime_log = out_dir / "runtime.log"
    dfa_log = out_dir / "dfa.log"
    network_log = out_dir / "network.log"

    cmd = [
        sys.executable, str(RUN_PYFEX),
        "--pyfex", str(interp),
        "--crash-recovery-enable", "1",
        "--force-exec-enable", "1",
        "--force-exec-merge-enable", "1",
        "--force-exec-global-limit", str(args.force_exec_limit),
        "--force-exec-location-limit", str(args.force_exec_location_limit),
        "--force-exec-loop-iter-limit", str(args.loop_limit),
        "--pyfex-scope-dir", str(scope_dir),
        "--pyfex-trace-log-file", str(trace_log),
        "--pyfex-runtime-log-file", str(runtime_log),
        "--dormant-func-log-file", str(dfa_log),
        "--network", args.network,
        "--network-log-file", str(network_log),
        "--timeout", str(args.timeout),
    ]
    if args.cwd:
        cmd.extend(["--cwd", str(Path(args.cwd).resolve())])
    if args.module:
        cmd.append("--module")
    cmd.append(args.program)
    if args.program_args:
        cmd.append("--")
        cmd.extend(args.program_args)

    print(f"[pyfexscan] running target under PyFEX -> {trace_log}", file=sys.stderr)
    subprocess.run(cmd, cwd=str(REPO_ROOT), env=_pyfex_env(args.provenance_mode))
    if not trace_log.is_file():
        raise SystemExit(f"PyFEX produced no trace at {trace_log}")
    return [trace_log]


def _resolve_sample_id(rank: int | None, sample_id: str | None) -> str:
    manifest = SAMPLES_DIR / "selection_manifest.csv"
    if not manifest.is_file():
        raise SystemExit(f"Selection manifest not found: {manifest}")
    with manifest.open("r", encoding="utf-8", newline="") as fp:
        for row in csv.DictReader(fp):
            if rank is not None and int(row["rank"]) == rank:
                return row["sample_id"]
            if sample_id is not None and row["sample_id"] == sample_id:
                return row["sample_id"]
    raise SystemExit("Requested sample not found in selection_manifest.csv")


def acquire_from_sample(args: argparse.Namespace) -> list[Path]:
    _require_interpreter(Path(args.pyfex).resolve())
    rank = None
    sid = None
    if args.sample.isdigit():
        rank = int(args.sample)
    else:
        sid = args.sample
    sample_id = _resolve_sample_id(rank, sid)

    cmd = [sys.executable, str(RUN_ONE_SAMPLE)]
    if rank is not None:
        cmd += ["--rank", str(rank)]
    else:
        cmd += ["--sample-id", sample_id]
    cmd += ["--timeout", str(args.timeout), "--network", args.network]

    print(f"[pyfexscan] running calibrated sample {sample_id} under PyFEX", file=sys.stderr)
    subprocess.run(cmd, cwd=str(REPO_ROOT), env=_pyfex_env(args.provenance_mode))

    log_dir = SAMPLES_DIR / "logs" / sample_id
    traces = sorted(log_dir.glob("*/behavior_trace.jsonl"))
    if not traces:
        raise SystemExit(f"No traces were produced under {log_dir}")
    return traces


